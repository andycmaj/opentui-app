import { defineCollection } from "astro:content";
import { glob } from "astro/loaders";
import { z } from "astro/zod";

const apps = defineCollection({
  loader: glob({ pattern: "*.mdx", base: "./src/content/apps" }),
  schema: z.object({
    name: z.string(),
    pitch: z.string(),
    status: z.enum(["stable", "beta"]),
    order: z.number(),
    repo: z.string(),
    requires: z.array(z.string()),
    configPath: z.string().optional(),
  }),
});

const docs = defineCollection({
  loader: glob({ pattern: "**/*.mdx", base: "./src/content/docs" }),
  schema: z.object({
    title: z.string(),
    // Shorter label for the sidebar; defaults to the lower-cased title.
    navLabel: z.string().optional(),
    description: z.string(),
    order: z.number(),
  }),
});

// Generated by `bun run api` (TypeDoc). Ids keep TypeDoc's file names, case
// included, so its cross-links resolve to these routes unchanged.
const api = defineCollection({
  loader: glob({
    pattern: "**/*.md",
    base: "./src/content/api",
    generateId: ({ entry }) => entry.replace(/\.md$/, ""),
  }),
});

export const collections = { apps, docs, api };
